NAMA = input("Masukan nama: ")
MATAKULIAH = input("Masukan mata kuliah: ")
nilai_tugas = input("Masukan nilai: ")
operasi = map(int, nilai_tugas.split())
# print(operasi)
rata_rata = list(operasi)
# print(rata_rata)
hasil = sum(rata_rata) / len(rata_rata)
print(f"Mahasiswa {NAMA} pada matakuliah {MATAKULIAH} rata-rata nilai tugasnya adalah {int(hasil)}")